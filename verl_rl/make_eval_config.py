#!/usr/bin/env python3
"""Write the OpenCompass config that scores all five roles on one suite.

The five roles are the point. Reporting only the merged model answers nothing:

    W_B       untuned base            what GRPO started from, on the base side
    W_I       untuned instruct        what the graft is bolted onto
    RL(W_B)   GRPO on the base        the base-initialised run
    RL(W_I)   GRPO on the instruct    the ordinary-RL baseline to beat
    W_shadow  W_I + (RL(W_B) - W_B)   the Shadow-FT graft

All five are prompted through the same chat template and the same datasets, so
the only difference between the columns is the weights. That includes the two
base-side entries: the merged model is an instruct model in every respect that
matters, and scoring the base checkpoints with a different prompt would confound
the comparison with a formatting difference.

    python verl_rl/make_eval_config.py --out opencompass/eval_verl_grpo.py
    python verl_rl/make_eval_config.py --out X --suite shadow
    python verl_rl/make_eval_config.py --out X --datasets aime2024,math500
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys


# (import path, symbol) for each benchmark, verified against the vendored
# OpenCompass tree by tests/test_eval_config.py. A typo here surfaces as an
# ImportError an hour into a run, so the test greps for the symbol.
DATASETS = {
    "aime2024": ("opencompass.configs.datasets.aime2024.aime2024_gen_17d799",
                 "aime2024_datasets"),
    "aime2025": ("opencompass.configs.datasets.aime2025.aime2025",
                 "aime2025_datasets"),
    "math500": ("opencompass.configs.datasets.math.math_500_gen",
                "math_datasets"),
    "gsm8k": ("opencompass.configs.datasets.gsm8k.gsm8k_0shot_v2_gen_17d799",
              "gsm8k_datasets"),
    "gpqa": ("opencompass.configs.datasets.gpqa.gpqa_gen_4baadb",
             "gpqa_datasets"),
    "olympiadbench": ("opencompass.configs.datasets.OlympiadBench.OlympiadBench_0shot_gen_be8b13",
                      "olympiadbench_datasets"),
    "teval": ("opencompass.configs.datasets.teval.teval_en_gen_slim",
              "teval_slim_datasets"),
}

SUITES = {
    # The recipe's own validation sets, so the final numbers are comparable with
    # what the training log reported. AMC23 is missing on purpose: the recipe
    # validates on it, and this OpenCompass tree has no config for it, so it is
    # covered during training (verl scores it with our reward function) but not
    # here. Adding an AMC23 dataset config is its own piece of work -- claiming
    # the suite covers it would be worse than the gap.
    "recipe": ["aime2024", "aime2025"],
    # The above plus what a GRPO'd math model is usually also reported on.
    "math": ["aime2024", "aime2025", "math500", "gsm8k", "olympiadbench", "gpqa"],
    # The set the repo's existing Shadow-FT SFT runs used, so the RL numbers land
    # in the same table as those.
    "shadow": ["math500", "gsm8k", "teval"],
    # Fastest thing that still moves: one small set.
    "fast": ["gsm8k"],
}

HEADER = '''# Auto-generated by verl_rl/make_eval_config.py -- do not edit by hand.
#
# Scores the five Shadow-FT roles on {suite_desc}.
#
#   cd opencompass && python3 ./run.py ./{basename} -w {work_dir}
#
# Every role is prompted through the same chat template; the only difference
# between them is the weights.

from mmengine.config import read_base

with read_base():
{imports}

datasets = sum((v for k, v in locals().items() if k.endswith('_datasets')), [])

from opencompass.models import {model_cls}

work_dir = '{work_dir}'

# (abbr, path). Order is the order they appear in the summary table.
MODELS = [
{models}
]

models = [
    dict(
        type={model_cls},
        abbr=abbr,
        path=path,
{engine_block}
        max_seq_len={max_seq_len},
        max_out_len={max_out_len},
        batch_size={batch_size},
        run_cfg=dict(num_gpus={num_gpus}),
    )
    for abbr, path in MODELS
]
'''

VLLM_ENGINE = """        model_kwargs=dict(
            tensor_parallel_size={tp},
            gpu_memory_utilization={gpu_util},
            max_model_len={max_seq_len},
            trust_remote_code=True,
        ),
        generation_kwargs=dict(temperature={temperature}, top_p=0.95),"""

TURBOMIND_ENGINE = """        engine_config=dict(session_len={max_seq_len}, max_batch_size=1024, tp={tp}),
        gen_config=dict(top_k=1, temperature={temperature}, top_p=0.9,
                        max_new_tokens={max_out_len}),"""


def read_config_sh(keys, config_path):
    """Ask config.sh for its values instead of duplicating the layout."""
    query = f"source {config_path} >/dev/null 2>&1; " + "; ".join(
        f'echo "${k}"' for k in keys
    )
    out = subprocess.run(["bash", "-c", query], capture_output=True, text=True)
    values = out.stdout.split("\n")
    return {k: (values[i].strip() if i < len(values) else "") for i, k in enumerate(keys)}


def main() -> int:
    here = os.path.dirname(os.path.abspath(__file__))
    repo = os.path.dirname(here)
    cfg = read_config_sh(
        ["PAIR_NAME", "BASE_MODEL", "INSTRUCT_MODEL", "EXPORT_DIR", "MERGED_DIR",
         "EVAL_SUITE", "EVAL_DATASETS", "EVAL_BACKEND", "EVAL_MAX_OUT_LEN",
         "EVAL_MAX_SEQ_LEN", "ROLLOUT_TP"],
        os.path.join(here, "config.sh"),
    )

    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=os.path.join(repo, "opencompass", "eval_verl_grpo.py"))
    ap.add_argument("--suite", default=cfg["EVAL_SUITE"] or "math", choices=sorted(SUITES))
    ap.add_argument("--datasets", default=cfg["EVAL_DATASETS"],
                    help="comma-separated, overrides --suite")
    ap.add_argument("--backend", default=cfg["EVAL_BACKEND"] or "vllm",
                    choices=["vllm", "turbomind"])
    ap.add_argument("--roles", default="base_baseline,instruct_baseline,rl_on_base,"
                                       "rl_on_instruct,shadow")
    ap.add_argument("--tp", type=int, default=int(cfg["ROLLOUT_TP"] or 1))
    ap.add_argument("--gpu-util", type=float, default=0.85)
    ap.add_argument("--temperature", type=float, default=0.0)
    ap.add_argument("--batch-size", type=int, default=256)
    ap.add_argument("--max-out-len", type=int, default=int(cfg["EVAL_MAX_OUT_LEN"] or 8192))
    ap.add_argument("--max-seq-len", type=int, default=int(cfg["EVAL_MAX_SEQ_LEN"] or 16384))
    args = ap.parse_args()

    names = ([d.strip() for d in args.datasets.split(",") if d.strip()]
             if args.datasets else SUITES[args.suite])
    unknown = [n for n in names if n not in DATASETS]
    if unknown:
        sys.exit(f"unknown dataset(s): {', '.join(unknown)}. "
                 f"Known: {', '.join(sorted(DATASETS))}")

    pair = cfg["PAIR_NAME"] or "verl-grpo"
    role_paths = {
        "base_baseline": (f"{pair}-W_B-base", cfg["BASE_MODEL"]),
        "instruct_baseline": (f"{pair}-W_I-instruct", cfg["INSTRUCT_MODEL"]),
        "rl_on_base": (f"{pair}-RL_W_B", os.path.join(cfg["EXPORT_DIR"], "base")),
        "rl_on_instruct": (f"{pair}-RL_W_I", os.path.join(cfg["EXPORT_DIR"], "instruct")),
        "shadow": (f"{pair}-W_shadow", cfg["MERGED_DIR"]),
    }
    roles = [r.strip() for r in args.roles.split(",") if r.strip()]
    bad = [r for r in roles if r not in role_paths]
    if bad:
        sys.exit(f"unknown role(s): {', '.join(bad)}")

    imports = "\n".join(
        f"    from {DATASETS[n][0]} import {DATASETS[n][1]}" for n in names
    )
    models = "\n".join(
        f"    ({role_paths[r][0]!r}, {role_paths[r][1]!r})," for r in roles
    )

    if args.backend == "vllm":
        model_cls = "VLLMwithChatTemplate"
        engine = VLLM_ENGINE.format(tp=args.tp, gpu_util=args.gpu_util,
                                    max_seq_len=args.max_seq_len,
                                    temperature=args.temperature)
    else:
        model_cls = "TurboMindModelwithChatTemplate"
        engine = TURBOMIND_ENGINE.format(tp=args.tp, max_seq_len=args.max_seq_len,
                                         temperature=args.temperature,
                                         max_out_len=args.max_out_len)

    work_dir = f"outputs/{pair}/"
    text = HEADER.format(
        suite_desc=", ".join(names),
        basename=os.path.basename(args.out),
        work_dir=work_dir,
        imports=imports,
        model_cls=model_cls,
        models=models,
        engine_block=engine,
        max_seq_len=args.max_seq_len,
        max_out_len=args.max_out_len,
        batch_size=args.batch_size,
        num_gpus=args.tp,
    )

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(text)

    print(f"wrote {args.out}")
    print(f"  datasets : {', '.join(names)}")
    print(f"  roles    : {', '.join(roles)}")
    print(f"  backend  : {args.backend} (tp={args.tp})")
    print()
    print("run it with:")
    print(f"  cd opencompass && python3 ./run.py ./{os.path.basename(args.out)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
